const {JSDOM}=require('jsdom');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path'),os=require('node:os');
const {spawn}=require('node:child_process');
const root=path.resolve(__dirname,'..');
const base='http://127.0.0.1:'+(process.env.ONTOLOGY_UI_PORT||'8767');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'ontology-ui-'));
const server=spawn(process.env.PYTHON||'python3',['-m','uvicorn','app.main:app','--host','127.0.0.1','--port',new URL(base).port],{cwd:root,env:{...process.env,ONTOLOGY_DB:path.join(temp,'test.sqlite3')},stdio:'ignore'});
let serverError;server.on('error',e=>serverError=e);
const cleanup=()=>{w.close();server.kill();};
server.on('close',()=>fs.rmSync(temp,{recursive:true,force:true}));
const dom=new JSDOM(fs.readFileSync(path.join(root,'static/index.html'),'utf8'),{url:base,runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,d=w.document;
w.fetch=(url,opts)=>fetch(new URL(url,base),opts);
const errors=[];w.addEventListener('error',e=>errors.push(e.message));
const until=async(fn)=>{for(let i=0;i<150;i++){if(fn())return;await new Promise(r=>setTimeout(r,20));}throw Error('UI condition timed out: '+d.querySelector('#alert').textContent);};
const get=s=>d.querySelector(s);
const submit=(form,button)=>form.dispatchEvent(new w.SubmitEvent('submit',{bubbles:true,cancelable:true,submitter:button}));
(async()=>{
 let ready=false;
 for(let i=0;i<100;i++){if(serverError)throw serverError;try{const r=await fetch(base+'/api/health');if(r.ok){ready=true;break;}}catch{}await new Promise(r=>setTimeout(r,50));}
 assert(ready,'API did not start');
 w.eval(fs.readFileSync(path.join(root,'static/app.js'),'utf8'));
 await until(()=>get('#connection').textContent.includes('已连接'));
 get('[data-page="knowledge"]').click();await until(()=>get('[data-doc="kb-release"]'));
 get('[data-doc="kb-release"]').click();await until(()=>get('#doc-reader .eyebrow')?.textContent.includes('kb-release'));
 let f=get('#revision-form');f.elements.namedItem('body').value='<script>window.injected=true</script> 来源已更新';f.elements.namedItem('reason').value='DOM集成测试';
 submit(f,f.querySelector('button'));await until(()=>get('#doc-reader .warning')?.textContent.includes('待复核'));
 assert(!w.injected);assert.equal(get('#doc-reader script'),null);
 assert(get('#doc-reader').textContent.includes('来源变更'));
 f=get('#review-form');f.elements.namedItem('reason').value='核对来源';submit(f,f.querySelector('[value="approve"]'));
 await until(()=>get('.relation-review'));
 f=get('.relation-review');f.elements.namedItem('reason').value='核实关系仍然成立';submit(f,f.querySelector('button'));
 await until(()=>get('#review-form')&&!get('.relation-review[data-relation="e3"]'));
 f=get('#review-form');f.elements.namedItem('reason').value='撤回演练';submit(f,f.querySelector('[value="withdraw"]'));
 await until(()=>get('#doc-reader .warning')?.textContent.includes('已撤回'));
 assert.equal(get('#revision-form'),null);
 const visible=await (await fetch(base+'/api/documents')).json();assert(!visible.some(d=>d.id==='kb-release'));
 assert.deepEqual(errors,[]);
 console.log('DOM/API integration passed: update → escaped diff → approve → relation review → withdraw → search blocked.');
 cleanup();
})().catch(e=>{console.error(e);cleanup();process.exitCode=1;});
